import os
import sys
import json
import time
import shutil
import signal
import base64
import tempfile
import subprocess
import threading
from pathlib import Path

PLAYLIST_URL = (
    "https://youtube.com/playlist?"
    "list=PLbB-zzxmyt-qxqhYuwRWiDCAFgH8bDgkR"
)

RESTREAM_KEY = "re_12012590_event263b321ab25446e5b8f3f975dabd2c6a"
RESTREAM_SERVER = "rtmp://live.restream.io/live"

COOKIES_B64 = os.getenv("YOUTUBE_COOKIES_B64", "").strip()
VIDEO_FILE = Path("/app/loop.mp4")

SAMPLE_RATE = 48000
CHANNELS = 2
CHUNK_SIZE = 65536

stop_event = threading.Event()
children = []
cookies_file = None


def log(message):
    print(message, flush=True)


def run_capture(command):
    return subprocess.run(
        command,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        check=True,
    ).stdout


def prepare_cookies():
    global cookies_file

    if not COOKIES_B64:
        raise RuntimeError(
            "Missing Railway Variable YOUTUBE_COOKIES_B64."
        )

    try:
        cookie_bytes = base64.b64decode(
            COOKIES_B64,
            validate=True,
        )
        cookie_text = cookie_bytes.decode("utf-8-sig")
    except Exception as exc:
        raise RuntimeError(
            "YOUTUBE_COOKIES_B64 is not valid Base64 UTF-8."
        ) from exc

    if not (
        cookie_text.startswith("# Netscape HTTP Cookie File")
        or cookie_text.startswith("# HTTP Cookie File")
        or cookie_text.startswith("# Generated by")
    ):
        raise RuntimeError(
            "Cookies file is not in Netscape format."
        )

    handle = tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        newline="\n",
        suffix=".txt",
        prefix="ytcookies_",
        delete=False,
    )
    cookies_file = handle.name

    with handle:
        handle.write(cookie_text)

    os.chmod(cookies_file, 0o600)
    log("[COOKIES] Loaded from Railway variable.")


def get_playlist():
    log("[PLAYLIST] Reading playlist...")

    data = json.loads(run_capture([
        "yt-dlp",
        "--cookies", cookies_file,
        "--flat-playlist",
        "--dump-single-json",
        "--no-warnings",
        PLAYLIST_URL,
    ]))

    videos = []

    for entry in data.get("entries") or []:
        if entry and entry.get("id"):
            videos.append(
                f"https://www.youtube.com/watch?v={entry['id']}"
            )

    if not videos:
        raise RuntimeError("Playlist is empty or unavailable.")

    log(f"[PLAYLIST] Found {len(videos)} tracks.")
    return videos


def terminate_process(proc):
    if proc and proc.poll() is None:
        proc.terminate()
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()


def stream_audio(video_urls, audio_pipe):
    index = 0

    while not stop_event.is_set():
        url = video_urls[index]
        track_number = index + 1
        index = (index + 1) % len(video_urls)

        log(f"[AUDIO] Track {track_number}/{len(video_urls)}")

        downloader = None
        converter = None

        try:
            downloader = subprocess.Popen([
                "yt-dlp",
                "--cookies", cookies_file,
                "--no-warnings",
                "--no-playlist",
                "--retries", "3",
                "-f", "bestaudio/best",
                "-o", "-",
                url,
            ], stdout=subprocess.PIPE, bufsize=0)
            children.append(downloader)

            converter = subprocess.Popen([
                "ffmpeg",
                "-hide_banner",
                "-loglevel", "error",
                "-i", "pipe:0",
                "-vn",
                "-f", "s16le",
                "-ar", str(SAMPLE_RATE),
                "-ac", str(CHANNELS),
                "pipe:1",
            ], stdin=downloader.stdout,
               stdout=subprocess.PIPE, bufsize=0)
            children.append(converter)

            if downloader.stdout:
                downloader.stdout.close()

            while not stop_event.is_set():
                chunk = converter.stdout.read(CHUNK_SIZE)
                if not chunk:
                    break
                audio_pipe.write(chunk)

            converter.wait()
            downloader.wait()

            if converter.returncode != 0 or downloader.returncode != 0:
                log("[WARN] Track failed; skipping to next track.")

        except (BrokenPipeError, OSError) as exc:
            if not stop_event.is_set():
                log(f"[AUDIO ERROR] {exc}")

        finally:
            terminate_process(converter)
            terminate_process(downloader)

            for proc in (converter, downloader):
                if proc in children:
                    children.remove(proc)

        if not stop_event.is_set():
            time.sleep(1)


def stop_all(*_):
    stop_event.set()

    for proc in list(children):
        terminate_process(proc)


def main():
    if not RESTREAM_KEY:
        raise RuntimeError("RESTREAM_KEY is empty.")

    if not VIDEO_FILE.is_file():
        raise FileNotFoundError("Missing /app/loop.mp4.")

    for tool in ("ffmpeg", "yt-dlp"):
        if not shutil.which(tool):
            raise RuntimeError(f"Missing required tool: {tool}")

    prepare_cookies()
    videos = get_playlist()

    # A FIFO allows FFmpeg to receive audio without storing the playlist.
    fifo_path = "/tmp/playlist_audio.pcm"

    if os.path.exists(fifo_path):
        os.unlink(fifo_path)

    os.mkfifo(fifo_path)

    output_url = f"{RESTREAM_SERVER}/{RESTREAM_KEY}"

    publisher = subprocess.Popen([
        "ffmpeg",
        "-hide_banner",
        "-loglevel", "info",
        "-nostdin",

        "-stream_loop", "-1",
        "-re", "-i", str(VIDEO_FILE),

        "-f", "s16le",
        "-ar", str(SAMPLE_RATE),
        "-ac", str(CHANNELS),
        "-i", fifo_path,

        "-map", "0:v:0",
        "-map", "1:a:0",

        "-vf",
        "scale=720:1280:force_original_aspect_ratio=decrease,"
        "pad=720:1280:(ow-iw)/2:(oh-ih)/2,"
        "setsar=1,format=yuv420p",

        "-c:v", "libx264",
        "-preset", "veryfast",
        "-pix_fmt", "yuv420p",
        "-r", "30",
        "-g", "60",
        "-b:v", "2200k",
        "-maxrate", "2200k",
        "-bufsize", "4400k",

        "-c:a", "aac",
        "-b:a", "128k",
        "-ar", "48000",
        "-ac", "2",

        "-f", "flv",
        output_url,
    ])
    children.append(publisher)

    try:
        log("[LIVE] Starting Restream output.")
        log("[VIDEO] loop.mp4 repeats continuously.")
        log("[STORAGE] Playlist audio is not saved.")

        # Open the FIFO for writing; FFmpeg opens its read end.
        with open(fifo_path, "wb", buffering=0) as audio_pipe:
            producer = threading.Thread(
                target=stream_audio,
                args=(videos, audio_pipe),
                daemon=True,
            )
            producer.start()

            while not stop_event.is_set():
                if publisher.poll() is not None:
                    raise RuntimeError(
                        f"FFmpeg exited: {publisher.returncode}"
                    )
                time.sleep(2)

    finally:
        stop_all()

        if publisher.poll() is None:
            terminate_process(publisher)

        if publisher in children:
            children.remove(publisher)

        if os.path.exists(fifo_path):
            os.unlink(fifo_path)

        if cookies_file and os.path.exists(cookies_file):
            os.unlink(cookies_file)


if __name__ == "__main__":
    signal.signal(signal.SIGTERM, stop_all)
    signal.signal(signal.SIGINT, stop_all)

    try:
        main()
    except Exception as exc:
        log(f"[ERROR] {exc}")
        sys.exit(1)
